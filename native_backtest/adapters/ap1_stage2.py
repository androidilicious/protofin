"""AP1 adapter: Stage 2 System A (8 macro surprises -> Ridge -> Black-Litterman), unchanged.

Development decisions come from running the canonical Stage 2 scorer itself (development mode).
Historical-window decisions cannot be produced before the opening: System A's walk-forward Ridge
and covariance use labels through t-2, which inside the protected window are protected returns.
They are generated by the scorer's own historical mode inside the scripted opening.
"""
from __future__ import annotations

import hashlib
from pathlib import Path
from typing import List

import pandas as pd

from native_backtest.framework.market import Market, decision_time_iso
from native_backtest.framework.records import DecisionRecord

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ["SPY", "IEF", "LQD"]


def build_records_from_stage2_run(run_dir: Path, market: Market) -> List[DecisionRecord]:
    port = pd.read_csv(run_dir / "stage2_portfolio_returns.csv")
    port = port[port["strategy"] == "A"]
    pred = pd.read_csv(run_dir / "stage2_predictions.csv")
    pred = pred[pred["system"] == "A"]
    files = {p: hashlib.sha256((run_dir / p).read_bytes()).hexdigest() for p in ("stage2_portfolio_returns.csv", "stage2_predictions.csv", "run_hash_manifest.json")}
    recs = []
    for row in port.itertuples():
        month = pd.Period(row.decision_month, "M")
        day = market.decision_dates[month]
        q = pred[pred["decision_month"] == row.decision_month].set_index("asset")["prediction_excess_return"]
        recs.append(DecisionRecord(
            system_id="AP1",
            decision_month=str(month),
            decision_time=decision_time_iso(day),
            info_cutoff=decision_time_iso(day),
            universe=ASSETS,
            target_weights={a: float(getattr(row, f"w_{a}")) for a in ASSETS},
            generation={"mode": "computed_native", "code": "stage2/scoring/stage2_backtest.py + stage2_portfolio.py (System A, unchanged)",
                        "run_spec": "stage2/scoring/stage2_run_spec_dev_v4.json", "run_files_sha256": files},
            forecast={"horizon_months": 1, "kind": "expected_excess_return_decimal", "values": {a: float(q[a]) for a in ASSETS}},
        ))
    return recs
