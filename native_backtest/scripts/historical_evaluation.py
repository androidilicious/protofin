#!/usr/bin/env python3
"""Final historical backtest: the one-time, confirmatory scoring of the protected window. RUN ONLY AFTER GO.

Scores the three primary approaches on the sealed window with the shared evaluator, exactly as on development
months: primary period 2024-01..2026-08, secondary period 2023-01..2023-12 reported separately.

  - Primary comparison: net CER differences JEV − Deterministic, Causal RAG − Deterministic and
    Causal RAG − JEV, block bootstrap (6-month blocks, 5000 reps, seed 20261027), one Holm family of three.
  - Supporting metrics: Sharpe ratio, maximum drawdown, volatility, cumulative return, turnover.
  - Passive Portfolio Reference (frozen 60% SPY / 40% IEF): secondary, with the accounting decomposition.
  - Agent Committee vs JEV: within-approach, reported separately, outside the Holm family.

Refuses to read or score anything unless ALL of these hold (checked before any outcome is loaded):
  1. a signed GO record (decision "GO", signed_by) whose frozen_decision_files_sha256 match the decision files;
  2. the opening token passed explicitly;
  3. the Causal RAG primary version recorded in native_backtest/config/approvals/ap3_primary_version.json and
     named identically in the GO record (ap3_primary_version);
  4. decision records for every protected month and every system, none generated by the engineering mock.

--check lists what is missing without scoring anything.

Usage (repository root):
  python -m native_backtest.scripts.historical_evaluation --check
  python -m native_backtest.scripts.historical_evaluation --go-record <signed GO json> --token <opening token>
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List

from native_backtest.framework.lock import WindowLocked, assert_scoring_allowed, file_sha256
from native_backtest.framework.market import load_config, months_between
from native_backtest.framework.records import read_jsonl

ROOT = Path(__file__).resolve().parents[2]
DEC = ROOT / "native_backtest/out/decisions"
OUT = ROOT / "native_backtest/out/historical"
PRIMARY_VERSION = ROOT / "native_backtest/config/approvals/ap3_primary_version.json"
SYSTEMS = ("AP1", "AP2B", "AP3")
WITHIN = ("AP2A",)


def periods(cfg: dict) -> Dict[str, list]:
    h = cfg["windows"]["historical_test"]
    return {"primary": months_between(*h["primary"]), "secondary_2023": months_between(*h["secondary"])}


def missing_prerequisites(cfg: dict, go_record: Path | None) -> List[str]:
    miss = []
    months = {str(m) for p in periods(cfg).values() for m in p}
    for s in SYSTEMS + WITHIN:
        f = DEC / f"{s}.jsonl"
        if not f.exists():
            miss.append(f"decision records {f.relative_to(ROOT)}")
            continue
        recs = read_jsonl(f)
        have = {r.decision_month for r in recs}
        lacking = sorted(months - have)
        if lacking:
            miss.append(f"{s}: no decision records for {len(lacking)} protected months ({lacking[0]}..{lacking[-1]})")
        if any(r.generation.get("mode") == "engineering_mock" for r in recs):
            miss.append(f"{s}: engineering-mock records present")
        # an exploratory (gate-failed) baseline is a diagnostic and can never become the confirmatory input,
        # whatever the GO record says
        if any(r.generation.get("exploratory") for r in recs):
            miss.append(f"{s}: records come from the EXPLORATORY gate-failed mode; the confirmatory test needs "
                        "decisions from a run that passed the reliability gates")
    if not PRIMARY_VERSION.exists():
        miss.append(f"approved Causal RAG primary version ({PRIMARY_VERSION.relative_to(ROOT)})")
    if go_record is None or not Path(go_record).exists():
        miss.append("signed GO record")
    else:
        g = json.loads(Path(go_record).read_text())
        if g.get("decision") != "GO" or not g.get("signed_by"):
            miss.append("GO record is not a signed GO")
        if PRIMARY_VERSION.exists() and g.get("ap3_primary_version") != json.loads(PRIMARY_VERSION.read_text()).get("version"):
            miss.append("GO record does not name the approved Causal RAG primary version")
    return miss


def evaluate(cfg: dict) -> dict:
    """The shared evaluation, identical to development_evaluation, on the protected periods."""
    from native_backtest.framework import benchmark as B
    from native_backtest.framework import metrics as M
    from native_backtest.framework.accounting import simulate_records, static_portfolio_records
    from native_backtest.framework.market import load_market

    mk = load_market(cfg)
    cost, delta = cfg["costs"]["cost_per_dollar_traded"], cfg["metrics"]["cer_delta"]
    recs = {s: read_jsonl(DEC / f"{s}.jsonl") for s in SYSTEMS + WITHIN}
    out = {"status": "CONFIRMATORY — protected window opened under a signed GO record", "periods": {}}
    for name, months in periods(cfg).items():
        ms = {str(m) for m in months}
        sims = {}
        for s in SYSTEMS + WITHIN:
            sel = [r for r in recs[s] if r.decision_month in ms]
            sims[s] = simulate_records(sel, mk, months, cost_per_dollar=cost)
            neutral = static_portfolio_records(f"{s}_NEUTRAL", cfg["systems"][s]["native_neutral_weights"], sel)
            sims[f"{s}_NEUTRAL"] = simulate_records(neutral, mk, months, cost_per_dollar=cost)
        bench = B.simulate(cfg, mk, months, [r for r in recs["AP1"] if r.decision_month in ms])
        primary = {f"{x}-{y}": M.paired_cer_contrast(sims[x], sims[y]) for x, y in cfg["primary_contrasts"]}
        holm = M.holm({k: v["p_two_sided_bootstrap"] for k, v in primary.items()})
        out["periods"][name] = {
            "months": [str(months[0]), str(months[-1]), len(months)],
            "metrics": {s: {**M.metrics(sims[s]), "cumulative_return": B.cumulative_return(sims[s])} for s in SYSTEMS + WITHIN},
            "vs_own_benchmark": {s: M.paired_cer_contrast(sims[s], sims[f"{s}_NEUTRAL"]) for s in SYSTEMS + WITHIN},
            "primary_contrasts": {k: {**v, **holm[k]} for k, v in primary.items()},
            "within_approach": {f"{x}-{y}": M.paired_cer_contrast(sims[x], sims[y]) for x, y in cfg["within_approach_contrasts"]},
            "passive_reference": {"metrics": M.metrics(bench),
                                  "systems": {s: {"vs_reference": B.relative(sims[s], bench, cfg),
                                                  "decomposition": B.decomposition(sims[s], sims[f"{s}_NEUTRAL"], bench, delta)} for s in SYSTEMS}}}
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="list missing prerequisites; scores nothing")
    ap.add_argument("--go-record", type=Path)
    ap.add_argument("--token")
    a = ap.parse_args(argv)
    cfg = load_config()
    miss = missing_prerequisites(cfg, a.go_record)
    if a.check:
        print(json.dumps({"ready": not miss, "missing": miss}, indent=1))
        return 0
    if miss:
        raise WindowLocked("protected window stays sealed: " + "; ".join(miss))
    hashes = {f"{s}.jsonl": file_sha256(DEC / f"{s}.jsonl") for s in SYSTEMS + WITHIN}
    months = [m for p in periods(cfg).values() for m in p]
    assert_scoring_allowed(months, protected_start=cfg["windows"]["protected"][0], go_record_path=a.go_record,
                           token=a.token, decision_file_hashes=hashes)
    rep = evaluate(cfg)
    OUT.mkdir(parents=True, exist_ok=True)
    rep["go_record"] = str(a.go_record)
    rep["decision_files_sha256"] = hashes
    (OUT / "historical_report.json").write_text(json.dumps(rep, indent=1, default=str) + "\n")
    print(f"wrote {(OUT / 'historical_report.json').relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
